"""Generate src/engine/pdgData.ts from the PDG Monte-Carlo mass/width file.

Usage:  python scripts/make-pdg-data.py mass_width_2025.txt > src/engine/pdgData.ts
Download the input from https://pdg.lbl.gov/2025/mcdata/mass_width_2025.txt
(masses and widths there are in GeV; this script converts to MeV).
"""
import re
import sys

WANT = [1, 2, 3, 4, 5, 6, 11, 13, 15, 22, 23, 24, 25,
        111, 211, 213, 113, 221, 331, 223, 333, 130, 310, 311, 321, 313, 323,
        411, 421, 431, 511, 531, 443, 2212, 2112, 3122, 3212, 2224]
src = sys.argv[1]
edition = re.search(r"FROM (\d{4}) EDITION", open(src, encoding="utf8").readline()).group(1)
rows = {}
for line in open(src, encoding="utf8"):
    if line.startswith("*") or not line.strip():
        continue
    ids = [int(line[i:i + 8]) for i in (0, 8, 16, 24) if line[i:i + 8].strip()]
    nums = re.findall(r"[-+]?\d+\.?\d*(?:E[-+]?\d+)?", line[32:106].replace("+-", "-"))
    fields = line[32:106].split()
    mass = float(fields[0]) if fields and not fields[0].startswith(("+", "-")) else None
    width = float(fields[3]) if len(fields) >= 6 else None
    for i in ids:
        rows[i] = (mass, width)

out = [
    "/* GENERATED by scripts/make-pdg-data.py - do not edit by hand.",
    f" * Source: PDG Review of Particle Physics, {edition} edition (Monte-Carlo mass/width file).",
    " * Masses and widths in MeV. width = null when the PDG lists none (e.g. K0, K0bar, quarks). */",
    "export const PDG_EDITION = '%s';" % edition,
    "export const PDG: Record<number, { massMeV: number; widthMeV: number | null }> = {",
]
for i in WANT:
    mass, width = rows[i]
    w = "null" if width is None else "%.10g" % (width * 1000)
    out.append(f"  {i}: {{ massMeV: {'%.10g' % (mass * 1000)}, widthMeV: {w} }},")
out.append("};")
print("\n".join(out))
